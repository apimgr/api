package tor

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
)

// generateTorrc renders the torrc content for the dedicated Tor process
// from Config, including Tor-owned persistent hidden-service state.
func generateTorrc(cfg Config, dataDir, hiddenServiceDir string, backendPort int) string {
	// Control connection always uses a runtime-selected localhost port -
	// never the system Tor default (9051), never hardcoded.
	controlConfig := "ControlPort 127.0.0.1:auto"

	// SocksPort: enabled (runtime port) only when outbound-via-Tor is
	// enabled; otherwise fully disabled - never the system Tor default
	// (9050).
	socksConfig := "SocksPort 0"
	if cfg.UseNetwork {
		socksConfig = "SocksPort 127.0.0.1:auto"
	}

	safeLogging := "1"
	if !cfg.SafeLogging {
		safeLogging = "0"
	}
	closeOnLimit := "0"
	if cfg.CloseCircuitOnStreamLimit {
		closeOnLimit = "1"
	}

	// Monthly bandwidth accounting is only emitted when a real cap is
	// configured; "unlimited" (or empty) disables the accounting block
	// entirely.
	accountingConfig := ""
	if cfg.MaxMonthlyBandwidth != "" && cfg.MaxMonthlyBandwidth != "unlimited" {
		accountingConfig = fmt.Sprintf(`
# Monthly bandwidth limit
AccountingStart month 1 00:00
AccountingMax %s`, cfg.MaxMonthlyBandwidth)
	}

	return fmt.Sprintf(`# ============================================================
# Tor Configuration - Generated by server binary
# This file is regenerated on every startup because the backend port is runtime-selected.
# Server settings from server.yml are reflected in every generated file.
# ============================================================

# SOCKS port for outbound connections (0 = disabled, auto = runtime port)
# NEVER uses default port 9050 - runtime detection only
%s

# Control connection
# NEVER uses default port 9051 - uses runtime localhost port on all OSes
%s

# Security Hardening
SafeLogging %s

# Circuit limits
MaxCircuitDirtiness 600
MaxClientCircuitsPending %d
LearnCircuitBuildTimeout 0
CircuitBuildTimeout %d

# Bandwidth limits per second (from config)
BandwidthRate %s
BandwidthBurst %s
%s

# Disable unused features - not a relay or exit
ExitRelay 0
ExitPolicy reject *:*
ORPort 0
DirPort 0

# Isolated daemon state and runtime control port
DataDirectory %s
ControlPortWriteToFile %s
CookieAuthentication 1
DisableNetwork 1
__OwningControllerProcess %d

# Hidden service optimizations
HiddenServiceSingleHopMode 0
VanguardsLiteEnabled 1

# Faster startup
FetchDirInfoEarly 1
FetchDirInfoExtraEarly 1

# Reduce memory usage
DisableDebuggerAttachment 1

# Tor-owned persistent v3 hidden service
HiddenServiceDir %s
HiddenServiceVersion 3
HiddenServiceNumIntroductionPoints %d
HiddenServiceMaxStreams %d
HiddenServiceMaxStreamsCloseCircuit %s
HiddenServicePort %d 127.0.0.1:%d
HiddenServiceExportCircuitID haproxy
	`, socksConfig, controlConfig, safeLogging, cfg.MaxCircuits, cfg.CircuitTimeout, cfg.BandwidthRate, cfg.BandwidthBurst, accountingConfig,
		strconv.Quote(dataDir), strconv.Quote(filepath.Join(dataDir, "control_port")), os.Getpid(), strconv.Quote(hiddenServiceDir),
		cfg.NumIntroPoints, cfg.MaxStreamsPerCircuit, closeOnLimit,
		cfg.VirtualPort, backendPort)
}
